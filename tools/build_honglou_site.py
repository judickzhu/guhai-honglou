def cn_hui(n):
    """1..120 → 中文数字（用于「第X回」检索变体）。"""
    d0 = "零一二三四五六七八九"
    if n <= 10:
        return d0[n] if n != 10 else "十"
    if n < 20:
        return "十" + (d0[n-10] if n % 10 else "")
    if n < 100:
        tens, ones = n // 10, n % 10
        return d0[tens] + "十" + (d0[ones] if ones else "")
    if n == 100: return "一百"
    if n < 110: return "一百" + d0[n-100]
    if n < 120: return "一百" + d0[(n-100)//10] + "十" + (d0[n%10] if n%10 else "")
    return "一百二十"
